/**
 * sync-version.mjs
 *
 * Prebuild script that reads `version = "x.y.z"` from the root pyproject.toml
 * and writes site/src/generated/version.ts so the Astro build can embed the
 * application version without any manual duplication.
 *
 * Fails hard (non-zero exit) if the version field is missing or ambiguous.
 * Never requires a TOML parser dependency — uses simple regex on the [project]
 * section only.
 */

import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = fileURLToPath(new URL('.', import.meta.url));
const siteDir = resolve(scriptDir, '..');
const pyprojectPath = resolve(siteDir, '..', 'pyproject.toml');
const outputDir = resolve(siteDir, 'src', 'generated');
const outputPath = resolve(outputDir, 'version.ts');

// Read pyproject.toml
let toml;
try {
  toml = readFileSync(pyprojectPath, 'utf8');
} catch (err) {
  console.error(`[sync-version] ERROR: Cannot read ${pyprojectPath}`);
  console.error(err);
  process.exit(1);
}

// Locate [project] section and parse version = "x.y.z" within it.
// Strategy: find [project] header, then look for version = "..." before the next [section].
const projectSectionMatch = toml.match(/\[project\]([\s\S]*?)(?=\n\[|\s*$)/);
if (!projectSectionMatch) {
  console.error('[sync-version] ERROR: [project] section not found in pyproject.toml');
  process.exit(1);
}

const projectSection = projectSectionMatch[1];
const versionMatches = [...projectSection.matchAll(/^version\s*=\s*"([^"]+)"/gm)];

if (versionMatches.length === 0) {
  console.error('[sync-version] ERROR: version field not found in [project] section');
  process.exit(1);
}

if (versionMatches.length > 1) {
  console.error(
    '[sync-version] ERROR: multiple version fields found in [project] section — ambiguous',
  );
  process.exit(1);
}

const version = versionMatches[0][1];

// Basic semver sanity check
if (!/^\d+\.\d+\.\d+/.test(version)) {
  console.error(`[sync-version] ERROR: version "${version}" does not look like a semver string`);
  process.exit(1);
}

// Write generated/version.ts
const content = `// AUTO-GENERATED by scripts/sync-version.mjs — do not edit manually.
// Source: pyproject.toml [project].version
// Re-generated on every \`bun run build\` via prebuild hook.
export const APP_VERSION = ${JSON.stringify(version)} as const;
`;

mkdirSync(outputDir, { recursive: true });
writeFileSync(outputPath, content, 'utf8');

console.log(`[sync-version] APP_VERSION = ${version} → ${outputPath}`);
